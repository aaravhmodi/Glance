"""Regenerate docs/results_experiments.md and results/charts/*.svg from results/raw/*.json.

No new measurements and no third-party packages (matplotlib is not installed here, so charts are plain SVG).
Every number in the generated markdown is computed from the raw JSON by this script:
    python3 offline/experiments/report.py
"""
import json
import os
from statistics import mean

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
RAW = os.path.join(ROOT, "results", "raw")
CHARTS = os.path.join(ROOT, "results", "charts")
DOC = os.path.join(ROOT, "docs", "results_experiments.md")


def load(name):
    with open(os.path.join(RAW, name)) as f:
        return json.load(f)


def clipname(c):
    return c.replace(".mp4", "")


def svg_bars(path, title, labels, values, unit, colors=("#2a7", "#c43")):
    """Horizontal bar chart with a zero line; positive bars green, negative red."""
    w, rowh, left = 760, 16, 250
    h = 50 + rowh * len(values)
    lo, hi = min(0.0, min(values)), max(0.0, max(values))
    span = (hi - lo) or 1.0
    sx = (w - left - 40) / span
    zero = left + (-lo) * sx
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" font-family="sans-serif" font-size="11">' % (w, h),
           '<rect width="100%%" height="100%%" fill="white"/><text x="8" y="18" font-size="13" font-weight="bold">%s</text>' % title,
           '<line x1="%.1f" y1="28" x2="%.1f" y2="%d" stroke="#333"/>' % (zero, zero, h - 14),
           '<text x="%.1f" y="%d" text-anchor="middle">0 %s (right of line: Glance better)</text>' % (zero, h - 2, unit)]
    for i, (lab, v) in enumerate(zip(labels, values)):
        y = 34 + i * rowh
        x0, x1 = sorted((zero, zero + v * sx))
        out.append('<text x="%d" y="%d" text-anchor="end">%s</text>' % (left - 6, y + 10, lab))
        out.append('<rect x="%.1f" y="%d" width="%.1f" height="12" fill="%s"/>' % (x0, y, max(x1 - x0, 0.5), colors[0] if v >= 0 else colors[1]))
        if v >= 0:
            out.append('<text x="%.1f" y="%d">%+.2f</text>' % (x1 + 3, y + 10, v))
        else:
            out.append('<text x="%.1f" y="%d" text-anchor="end">%+.2f</text>' % (x0 - 3, y + 10, v))
    out.append("</svg>")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out))


def svg_lines(path, title, xs, series, unit):
    w, h, l, r, t, b = 560, 320, 60, 150, 40, 40
    ys = [v for s in series.values() for v in s]
    lo, hi = min(ys + [0.0]), max(ys + [0.0])
    pad = (hi - lo) * 0.1 or 1
    lo, hi = lo - pad, hi + pad

    def X(x):
        return l + (x - min(xs)) / ((max(xs) - min(xs)) or 1) * (w - l - r)

    def Y(y):
        return t + (hi - y) / (hi - lo) * (h - t - b)
    pal = ["#1b6ca8", "#c43", "#2a7", "#a6a", "#888", "#d90"]
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" font-family="sans-serif" font-size="11">' % (w, h),
           '<rect width="100%%" height="100%%" fill="white"/><text x="8" y="18" font-size="13" font-weight="bold">%s</text>' % title,
           '<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" stroke="#333" stroke-dasharray="4"/>' % (l, Y(0), w - r, Y(0)),
           '<text x="%d" y="%d">realised mean tracker error (deg)</text>' % (l, h - 8),
           '<text x="8" y="%d">%s</text>' % (t + 4, unit)]
    for x in xs:
        out.append('<text x="%.1f" y="%d" text-anchor="middle">%g</text>' % (X(x), h - b + 14, x))
    for i, (name, s) in enumerate(series.items()):
        c = pal[i % len(pal)]
        pts = " ".join("%.1f,%.1f" % (X(x), Y(v)) for x, v in zip(xs, s))
        out.append('<polyline fill="none" stroke="%s" stroke-width="2" points="%s"/>' % (c, pts))
        out.append('<text x="%d" y="%d" fill="%s">%s</text>' % (w - r + 8, t + 14 * i + 10, c, name))
    out.append("</svg>")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out))


def main():
    A, B = load("exp_a.json"), load("exp_b.json")
    T, E = load("exp_transport.json"), load("exp_tracker.json")
    notes = sorted(set(A["notes"] + B["notes"] + T["notes"] + E["notes"]))
    L = []
    w = L.append
    w("# Glance — experiment results (generated)")
    w("")
    w("**Generated by `python3 offline/experiments/report.py` from `results/raw/*.json`; do not edit by hand.** "
      "The raw data come from `python3 offline/experiments/run.py --ab` (A, B) and `--t8` (transport, tracker error).")
    w("")
    w("**All gaze traces are SYNTHETIC (seeded generator, `traces.py`), all content is the three real 'call' clips in `web/public/clips/` "
      "(talking heads, easy content). Codec: libvpx-vp9 realtime CBR, identical flags for baseline and Glance; they differ only in the input frames. "
      "Quality is measured with PSNR/SSIM inside a disc of the nominal fovea radius around the (true) gaze and compared with the untouched source. "
      "Not measured: " + "; ".join(notes) + ". No real webcam tracking data is involved: tracker error is simulated (T8).**")
    w("")

    # ---- Experiment B
    rb = B["rows"]
    gains = [r["foveal_psnr_gain_db"] for r in rb]
    pos = [r for r in rb if r["foveal_psnr_gain_db"] > 0]
    worst = min(rb, key=lambda r: r["foveal_psnr_gain_db"])
    best = max(rb, key=lambda r: r["foveal_psnr_gain_db"])
    w("## Claim 2: same bandwidth, better quality where it matters (Experiment B, equal CBR cap)")
    w("")
    w("Reproduce: `python3 offline/experiments/run.py --ab && python3 offline/experiments/report.py`")
    w("")
    w("**Result: the claim is NOT supported on this content.** %d conditions: mean foveal-PSNR gain of Glance over baseline %+.2f dB, "
      "best %+.2f dB (%s %dp %d kbps, %g deg), worst %+.2f dB (%s %dp %d kbps, %g deg). Glance is better in %d of %d conditions."
      % (len(rb), mean(gains), best["foveal_psnr_gain_db"], clipname(best["clip"]), best["res"], best["cap_kbps"], best["fovea_deg"],
         worst["foveal_psnr_gain_db"], clipname(worst["clip"]), worst["res"], worst["cap_kbps"], worst["fovea_deg"], len(pos), len(rb)))
    w("")
    w("| Clip | Res | Cap kbps | Fovea deg | Seed | kbps base / Glance | Foveal PSNR base / Glance (dB) | gain dB | worst-frame foveal PSNR base / Glance | foveal SSIM base / Glance |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for r in rb:
        x, y = r["baseline"], r["glance"]
        w("| %s | %dp | %d | %g | %d | %.0f / %.0f | %.2f / %.2f | %+.2f | %.1f / %.1f | %.3f / %.3f |" % (
            clipname(r["clip"]), r["res"], r["cap_kbps"], r["fovea_deg"], r["seed"], x["kbps"], y["kbps"],
            x["foveal_psnr"]["mean"], y["foveal_psnr"]["mean"], r["foveal_psnr_gain_db"],
            x["foveal_psnr"]["worst"], y["foveal_psnr"]["worst"], x["foveal_ssim"]["mean"], y["foveal_ssim"]["mean"]))
    w("")
    labs = ["%s %dp %dk %gdeg s%d" % (clipname(r["clip"]).replace("call-", ""), r["res"], r["cap_kbps"], r["fovea_deg"], r["seed"]) for r in rb]
    svg_bars(os.path.join(CHARTS, "exp_b_gain.svg"), "Exp. B: foveal PSNR gain of Glance at equal CBR cap (dB, synthetic gaze)", labs, gains, "dB")
    w("![Exp B](../results/charts/exp_b_gain.svg)")
    w("")

    # ---- Experiment A
    ra = A["rows"]
    reached = [r for r in ra if r["reached"]]
    sav = [r["percent_saved"] for r in reached]
    w("## Claim 1: same quality, less bandwidth (Experiment A, bisection)")
    w("")
    w("Reproduce: same command as above. For each condition the baseline is encoded at a target cap; the script then searches for the lowest Glance cap "
      "whose foveal PSNR is within %.1f dB of the baseline's (`reached`); otherwise the row says not reached." % ra[0]["tol_db"])
    w("")
    w("**Result: weak and not reliable.** Quality parity was reached in %d of %d conditions with savings of %s (mean %.1f %%, worst reached %.1f %%); "
      "NOT reached in %d conditions (listed below; they are not averaged in)."
      % (len(reached), len(ra), "%.1f to %.1f %%" % (min(sav), max(sav)) if sav else "n/a", mean(sav) if sav else 0, min(sav) if sav else 0, len(ra) - len(reached)))
    w("")
    w("| Clip | Res | Fovea deg | Seed | Baseline target kbps | Baseline kbps | Baseline foveal PSNR | Goal (>=) | Glance kbps | Saved % | Glance foveal PSNR |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in ra:
        g = r["glance"]
        w("| %s | %dp | %g | %d | %d | %.0f | %.2f | %.2f | %s | %s | %s |" % (
            clipname(r["clip"]), r["res"], r["fovea_deg"], r["seed"], r["baseline_target_kbps"], r["baseline"]["kbps"],
            r["baseline"]["foveal_psnr"]["mean"], r["goal_foveal_psnr"],
            ("%.0f" % g["kbps"]) if r["reached"] else "not reached", ("%.1f" % r["percent_saved"]) if r["reached"] else "-",
            ("%.2f" % g["foveal_psnr"]["mean"]) if g else "-"))
    w("")
    sl = ["%s %dp %gdeg s%d" % (clipname(r["clip"]).replace("call-", ""), r["res"], r["fovea_deg"], r["seed"]) for r in ra]
    svg_bars(os.path.join(CHARTS, "exp_a_saved.svg"), "Exp. A: % bandwidth saved at equal foveal PSNR (0 = parity not reached)", sl,
             [r["percent_saved"] if r["reached"] else 0.0 for r in ra], "%")
    w("![Exp A](../results/charts/exp_a_saved.svg)")
    w("")

    # ---- Tracker error
    re_ = E["rows"]
    w("## Where Glance loses: tracker error + 100 ms lag (T8, simulated)")
    w("")
    w("Reproduce: `python3 offline/experiments/run.py --t8 && python3 offline/experiments/report.py` (~35 min). Fovea centre = true gaze 100 ms old plus AR(1) noise; "
      "quality scored at the TRUE gaze in a 5 deg disc; baseline at the same cap. 'adaptive' = fovea radius grows with the error.")
    w("")
    w("| Clip | Cap kbps | Radius mode | Target error deg | Realised mean error deg | Foveal PSNR gain (dB) | Foveal SSIM gain | Full-frame PSNR gain (dB) |")
    w("|---|---|---|---|---|---|---|---|")
    series = {}
    for r in re_:
        w("| %s | %d | %s | %g | %.1f | %+.2f | %+.3f | %+.2f |" % (clipname(r["clip"]), r["cap_kbps"], r["radius_mode"], r["tracker_error_deg"],
                                                              r["realised_mean_error_deg"], r["foveal_psnr_gain_db"], r["foveal_ssim_gain"], r["full_psnr_gain_db"]))
        series.setdefault("%s %dk %s" % (clipname(r["clip"]).replace("call-", ""), r["cap_kbps"], r["radius_mode"]), []).append((r["realised_mean_error_deg"], r["foveal_psnr_gain_db"]))
    w("")
    allg = [r["foveal_psnr_gain_db"] for r in re_]
    w("Foveal PSNR gain over all %d tracker-error conditions: mean %+.2f dB, best %+.2f dB, worst %+.2f dB; positive in %d of %d."
      % (len(allg), mean(allg), max(allg), min(allg), sum(1 for g in allg if g > 0), len(allg)))
    w("")
    fixed = {k: v for k, v in series.items() if k.endswith("fixed") and len(v) > 1}
    if fixed:
        xs = [round(x, 1) for x, _ in next(iter(fixed.values()))]
        if all([round(x, 1) for x, _ in v] == xs for v in fixed.values()):
            svg_lines(os.path.join(CHARTS, "tracker_error.svg"), "Foveal PSNR gain vs tracker error (fixed 5 deg fovea)", xs,
                      {k: [g for _, g in v] for k, v in fixed.items()}, "dB")
            w("![Tracker error](../results/charts/tracker_error.svg)")
            w("")

    # ---- Transport
    w("## Loss and jitter (T8 transport model, 2 % packet loss, no retransmission)")
    w("")
    w("This model is pessimistic: frames are frozen until the next keyframe, so most frames are frozen for BOTH streams and the comparison is dominated by freezes. "
      "Differences are inside the noise of %d seeds; no claim is made." % len(T["rows"][0]["net_seeds"]))
    w("")
    w("| Clip | Cap kbps | Gain clean (dB) | Gain lossy (dB) | Frozen fraction base / Glance (lossy, mean) | Foveal PSNR lossy base / Glance (mean; worst seed) |")
    w("|---|---|---|---|---|---|")
    for r in T["rows"]:
        bl, gl = r["baseline"]["lossy"], r["glance"]["lossy"]
        w("| %s | %d | %+.2f | %+.2f | %.2f / %.2f | %.2f (%.2f) / %.2f (%.2f) |" % (
            clipname(r["clip"]), r["cap_kbps"], r["foveal_psnr_gain_db_clean"], r["foveal_psnr_gain_db_lossy"],
            bl["frozen_fraction"]["mean"], gl["frozen_fraction"]["mean"], bl["foveal_psnr"]["mean"], bl["foveal_psnr"]["worst"],
            gl["foveal_psnr"]["mean"], gl["foveal_psnr"]["worst"]))
    w("")

    # ---- Headline table
    w("## Headline numbers (synthetic gaze, call clips, VP9 CBR; VMAF not available)")
    w("")
    w("| Content | Res | Network | Codec | Fovea | Baseline kbps | Glance kbps | % saved | Foveal PSNR base/Glance | Foveal VMAF base/Glance |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for r in sorted(reached, key=lambda r: -r["percent_saved"])[:3]:
        w("| %s | %dp | clean, Exp. A | VP9 | %g deg | %.0f | %.0f | %.1f | %.2f / %.2f | n/a |" % (
            clipname(r["clip"]), r["res"], r["fovea_deg"], r["baseline"]["kbps"], r["glance"]["kbps"], r["percent_saved"],
            r["baseline"]["foveal_psnr"]["mean"], r["glance"]["foveal_psnr"]["mean"]))
    for r in (best, worst):
        w("| %s | %dp | CBR %d kbps, Exp. B (%s case) | VP9 | %g deg | %.0f | %.0f | %.1f | %.2f / %.2f | n/a |" % (
            clipname(r["clip"]), r["res"], r["cap_kbps"], "best" if r is best else "worst", r["fovea_deg"], r["baseline"]["kbps"], r["glance"]["kbps"],
            100 * (1 - r["glance"]["kbps"] / r["baseline"]["kbps"]), r["baseline"]["foveal_psnr"]["mean"], r["glance"]["foveal_psnr"]["mean"]))
    w("")
    w("## Honest summary")
    w("")
    w("- With the current pre-filter-only Glance (blur and downscale outside the fovea, then a standard VP9 encode), on easy talking-head clips and with synthetic gaze, "
      "the equal-quality saving is small or absent and the equal-bandwidth quality gain is mostly negative. This is what the data say; we do not claim the pitch numbers.")
    w("- Not tested yet: busy/screen/game content (Xiph downloads were refused in the unattended runs, task T7b), real webcam gaze traces, VMAF / FovVideoVDP, "
      "encoders with true per-region QP (not available in WebCodecs).")
    w("- The in-browser smoke test measures ~50 % fewer kbps at the same constant QP over 11 frame pairs; that is a same-QP size comparison (the foveal PSNR is similar) "
      "and is not the same as the CBR experiments above. Do not mix them.")
    w("")
    os.makedirs(os.path.dirname(DOC), exist_ok=True)
    with open(DOC, "w") as f:
        f.write("\n".join(L))
    print("wrote", DOC, "and charts in", CHARTS)


if __name__ == "__main__":
    main()
